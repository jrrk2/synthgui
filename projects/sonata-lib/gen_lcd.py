#!/usr/bin/env python3
"""Generate lcd_font.v and lcd_init_rom.v for lcd_dbg.v.

The font is font8x8_basic.h (public domain).  The init ROM is the three ST7735
scripts of sonata-system's vendor/display_drivers/st7735/lcd_st7735_init.h
(init_script_b, _r, _r3), run in that order as its lcd_st7735_init() does.

ROM entry = {type[2:0], data[7:0]}:
  0 command byte, CS released after   1 data byte, CS released after
  2 delay data milliseconds           3 end of list
  4 command byte, CS held (RAMWR)     5 lcd_rst low   6 lcd_rst high
"""
import re
from pathlib import Path

here = Path(__file__).parent
CMD, DAT, DLY, END, CMDK, RSTL, RSTH = range(7)
C = dict(SWRESET=0x01, SLPOUT=0x11, NORON=0x13, INVOFF=0x20, DISPON=0x29, CASET=0x2A,
         RASET=0x2B, RAMWR=0x2C, MADCTL=0x36, COLMOD=0x3A, FRMCTR1=0xB1, FRMCTR2=0xB2,
         FRMCTR3=0xB3, INVCTR=0xB4, DISSET5=0xB6, PWCTR1=0xC0, PWCTR2=0xC1, PWCTR3=0xC2,
         PWCTR4=0xC3, PWCTR5=0xC4, VMCTR1=0xC5, PWCTR6=0xFC, GMCTRP1=0xE0, GMCTRN1=0xE1)

# (command, [args], delay_ms or None)
# 0x68 = MV|MX|BGR; 0xA8 = MV|MY|BGR is the same landscape turned 180 degrees
MADCTL = 0xA8

script_b = [
    ("SWRESET", [], 50), ("SLPOUT", [], 500), ("COLMOD", [0x05], 10),
    ("FRMCTR1", [0x00, 0x06, 0x03], 10), ("MADCTL", [MADCTL], None),
    ("DISSET5", [0x15, 0x02], None), ("INVCTR", [0x0], None),
    ("PWCTR1", [0x02, 0x70], 10), ("PWCTR2", [0x05], None), ("PWCTR3", [0x01, 0x02], None),
    ("VMCTR1", [0x3C, 0x38], 10), ("PWCTR6", [0x11, 0x15], None),
    ("GMCTRP1", [0x09, 0x16, 0x09, 0x20, 0x21, 0x1B, 0x13, 0x19,
                 0x17, 0x15, 0x1E, 0x2B, 0x04, 0x05, 0x02, 0x0E], None),
    ("GMCTRN1", [0x0B, 0x14, 0x08, 0x1E, 0x22, 0x1D, 0x18, 0x1E,
                 0x1B, 0x1A, 0x24, 0x2B, 0x06, 0x06, 0x02, 0x0F], 10),
    ("CASET", [0x00, 0x02, 0x00, 0x81], None), ("RASET", [0x00, 0x02, 0x00, 0x81], None),
    ("NORON", [], 10), ("DISPON", [], 500),
]
script_r = [
    ("SWRESET", [], 150), ("SLPOUT", [], 500),
    ("FRMCTR1", [0x00, 0x02, 0x02], None), ("FRMCTR2", [0x00, 0x02, 0x02], None),
    ("FRMCTR3", [0x00, 0x02, 0x02, 0x00, 0x02, 0x02], None), ("INVCTR", [0x07], None),
    ("PWCTR1", [0xA2, 0x02, 0x84], None), ("PWCTR2", [0xC5], None),
    ("PWCTR3", [0x0A, 0x00], None), ("PWCTR4", [0x8A, 0x2A], None),
    ("PWCTR5", [0x8A, 0xEE], None), ("VMCTR1", [0x0E], None), ("INVOFF", [], None),
    ("MADCTL", [MADCTL], None), ("COLMOD", [0x05], None),
]
script_r3 = [
    ("GMCTRP1", [0x02, 0x1c, 0x07, 0x12, 0x37, 0x32, 0x29, 0x2d,
                 0x29, 0x25, 0x2B, 0x39, 0x00, 0x01, 0x03, 0x10], None),
    ("GMCTRN1", [0x03, 0x1d, 0x07, 0x06, 0x2E, 0x2C, 0x29, 0x2D,
                 0x2E, 0x2E, 0x37, 0x3F, 0x00, 0x00, 0x02, 0x10], None),
    ("NORON", [], 10), ("DISPON", [], 100),
]

def delay(ms):
    out = []
    while ms > 0:
        out.append((DLY, min(ms, 255)))
        ms -= 255
    return out

rom = [(RSTL, 0)] + delay(10) + [(RSTH, 0)] + delay(120)
for s in (script_b, script_r, script_r3):
    for cmd, args, ms in s:
        rom.append((CMD, C[cmd]))
        rom += [(DAT, a) for a in args]
        if ms:
            rom += delay(ms)
rom.append((END, 0))
HEADER = 256  # frame header: set the window to the whole 160x128 panel, start RAM write
assert len(rom) < HEADER, len(rom)
rom += [(END, 0)] * (HEADER - len(rom))
rom += [(CMD, C["CASET"]), (DAT, 0), (DAT, 0), (DAT, 0), (DAT, 159),
        (CMD, C["RASET"]), (DAT, 0), (DAT, 0), (DAT, 0), (DAT, 127),
        (CMDK, C["RAMWR"]), (END, 0)]

with open(here / "lcd_init_rom.v", "w") as f:
    f.write("// generated by gen_lcd.py -- do not edit\n"
            "// {type[2:0], data[7:0]}; the frame header starts at 256\n"
            "module lcd_init_rom (\n    input wire clk,\n    input wire [8:0] a,\n"
            "    output reg [10:0] q\n);\n    always @(posedge clk)\n        case (a)\n")
    for i, (t, d) in enumerate(rom):
        if (t, d) != (END, 0) or i == 0 or rom[i - 1] != (END, 0) or i >= HEADER:
            f.write(f"            9'd{i}: q <= {{3'd{t}, 8'h{d:02x}}};\n")
    f.write("            default: q <= {3'd3, 8'h00};\n        endcase\nendmodule\n")

font = {}
txt = (here / "font8x8_basic.h").read_text()
rows = re.findall(r"\{\s*((?:0x[0-9A-Fa-f]{2}\s*,?\s*){8})\}", txt)
assert len(rows) == 128, len(rows)
with open(here / "lcd_font.v", "w") as f:
    f.write("// generated by gen_lcd.py from font8x8_basic.h (public domain, D. Hepper / IBM VGA)\n"
            "// q[0] is the leftmost pixel of the row\n"
            "module lcd_font (\n    input wire clk,\n    input wire [6:0] ch,\n"
            "    input wire [2:0] row,\n    output reg [7:0] q\n);\n"
            "    always @(posedge clk)\n        case ({ch, row})\n")
    for c, r in enumerate(rows):
        for y, b in enumerate(re.findall(r"0x([0-9A-Fa-f]{2})", r)):
            if int(b, 16):
                f.write(f"            10'd{c * 8 + y}: q <= 8'h{b.lower()};\n")
    f.write("            default: q <= 8'h00;\n        endcase\nendmodule\n")
print(len(rom), "rom entries")
