#!/usr/bin/env python3
"""Generate hyperram.v: LiteX's HyperRAM core (litex/soc/cores/hyperbus.py) as one Verilog module.

    PYTHONPATH=<migen>:<litex> python3.12 gen_hyperram.py

LiteX and migen are needed only to regenerate; the generated file is committed and the
build does not use them.  Generated from LiteX b91b9c6bb (hyperbus.py identical to master of 2026-10).
HR_LATENCY / HR_MODE in the environment override the defaults below.

4:1 clock ratio: the core and the SDR PHY run in one clock, "sys"; the HyperRAM clock is sys/4
(80 MHz -> 20 MHz).  The pads are plain signals -- the top level puts the IOBUFs on dq and rwds.
Wishbone: 32-bit, word addressed, 2M words = 8 MB; consecutive addresses are one linear burst.
The core never ends a burst by itself: the master must, inside the HyperRAM's tCSM (4 us).
"""
import os
import sys
from migen import Signal
from migen.fhdl import verilog
from litex.soc.cores.hyperbus import HyperRAM

# Variable latency, 4 clocks, with the device set the same (CR0 0x8FF7: latency code 1111 = 4 clocks at up
# to 100 MHz, variable, legacy burst, 32 bytes).  Equal settings are what line up: in simulation against
# lowRISC's W956 model (the device Sonata's own controller runs, in variable latency) this passes with
# zero errors for 3..7 clocks when core and device agree, and never in fixed (2x) latency, where one
# latency step is four clock edges and the core and the model differ by two.
LATENCY = int(os.environ.get('HR_LATENCY', 4))
MODE = os.environ.get('HR_MODE', 'variable')


def sig(width, name):
    s = Signal(width, name=name)
    return s


class Pads:
    pass


pads = Pads()
pads.rst_n = sig(1, "hr_rst_n")
pads.cs_n = sig(1, "hr_cs_n")
pads.clk_p = sig(1, "hr_ck_p")
pads.clk_n = sig(1, "hr_ck_n")
pads.dq_o = sig(8, "hr_dq_o")
pads.dq_i = sig(8, "hr_dq_i")
pads.dq_oe = sig(1, "hr_dq_oe")
pads.rwds_o = sig(1, "hr_rwds_o")
pads.rwds_i = sig(1, "hr_rwds_i")
pads.rwds_oe = sig(1, "hr_rwds_oe")

dut = HyperRAM(pads, latency=LATENCY, latency_mode=MODE, clk_ratio="4:1",
               with_bursting=True, with_csr=False)
bus, core = dut.bus, dut.core

# the register port: identification and configuration registers
reg = core.reg
named = {
    "wb_cyc": bus.cyc, "wb_stb": bus.stb, "wb_we": bus.we, "wb_cti": bus.cti, "wb_sel": bus.sel,
    "wb_adr": bus.adr, "wb_dat_w": bus.dat_w, "wb_ack": bus.ack, "wb_dat_r": bus.dat_r,
    "reg_stb": reg.stb, "reg_we": reg.we, "reg_adr": reg.adr, "reg_dat_w": reg.dat_w,
    "reg_ack": reg.ack, "reg_dat_r": reg.dat_r,
    "hr_reset": core.rst,
}
for n, s in named.items():
    s.name_override = n

ios = set(named.values()) | {getattr(pads, k) for k in vars(pads)}
out = verilog.convert(dut, ios=ios, name="litex_hyperram")
text = str(out)
with open(sys.argv[1] if len(sys.argv) > 1 else "hyperram.v", "w") as f:
    f.write("// generated by gen_hyperram.py from LiteX's HyperRAM core -- do not edit\n" + text)
print("wrote", len(text.splitlines()), "lines")
