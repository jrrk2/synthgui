#!/usr/bin/env python3
"""Turn sonata-lib's generated case-statement ROMs (lcd_font.v, lcd_init_rom.v) into memories initialised from hex
files (rtl/lcd_font.v + lcd_font.hex, rtl/lcd_init_rom.v + lcd_init_rom.hex).  At 50 MHz the case statements map to
a ~20-LUT chain; as memories they land in block RAM.  Run from this directory."""
import re, pathlib
lib = pathlib.Path("../sonata-lib")

font = [0] * 1024
for a, v in re.findall(r"10'd(\d+): q <= 8'h([0-9a-f]+);", (lib / "lcd_font.v").read_text()):
    font[int(a)] = int(v, 16)
pathlib.Path("lcd_font.hex").write_text("".join("%02x\n" % v for v in font))
pathlib.Path("rtl/lcd_font.v").write_text("""// generated by gen_lcd_roms.py from sonata-lib/lcd_font.v (font8x8_basic.h, public domain, D. Hepper / IBM VGA)
// q[0] is the leftmost pixel of the row
module lcd_font (
    input wire clk,
    input wire [6:0] ch,
    input wire [2:0] row,
    output reg [7:0] q
);
    reg [7:0] rom [0:1023];
    initial $readmemh("lcd_font.hex", rom);
    always @(posedge clk) q <= rom[{ch, row}];
endmodule
""")

init = [0x300] * 512
for a, t, v in re.findall(r"9'd(\d+): q <= \{3'd(\d), 8'h([0-9a-f]+)\};", (lib / "lcd_init_rom.v").read_text()):
    init[int(a)] = (int(t) << 8) | int(v, 16)
pathlib.Path("lcd_init_rom.hex").write_text("".join("%03x\n" % v for v in init))
pathlib.Path("rtl/lcd_init_rom.v").write_text("""// generated by gen_lcd_roms.py from sonata-lib/lcd_init_rom.v -- {type[2:0], data[7:0]}; the frame header starts at 256
module lcd_init_rom (
    input wire clk,
    input wire [8:0] a,
    output reg [10:0] q
);
    reg [10:0] rom [0:511];
    initial $readmemh("lcd_init_rom.hex", rom);
    always @(posedge clk) q <= rom[a];
endmodule
""")
print(sum(1 for v in font if v), "font bytes,", sum(1 for v in init if v != 0x300), "init entries")
