#!/usr/bin/env python3
"""Write the BIOS's flash partition table from the device tree's MTD partitions (the children of the mtd-rom node).

    dts_partitions.py kernel/sonata-ram.dts ../bios/partitions.h

The same table is what Linux sees as /dev/mtdN, so `tftpflash rootfs.romfs rootfs` writes where the kernel reads.
"""
import re, sys

src = open(sys.argv[1]).read()
m = re.search(r'flash@[0-9a-fA-F]+\s*\{\s*compatible\s*=\s*"mtd-rom"', src)
if not m:
    sys.exit("no mtd-rom node in " + sys.argv[1])
body = src[m.end():]
parts = re.findall(r'@([0-9a-fA-F]+)\s*\{\s*label\s*=\s*"([^"]+)"\s*;\s*reg\s*=\s*<\s*(0x[0-9a-fA-F]+)\s+(0x[0-9a-fA-F]+)\s*>', body)
if not parts:
    sys.exit("no partitions found")
out = ["/* Generated by linux/tools/dts_partitions.py from kernel/sonata-ram.dts: do not edit. */",
       "static const struct tflash_part { const char *label; unsigned long off, size; } tflash_parts[] = {"]
for at, label, off, size in parts:
    assert int(at, 16) == int(off, 16), "unit address and reg differ for " + label
    out.append('\t{ "%s", %s, %s },' % (label, off, size))
out.append("};")
open(sys.argv[2], "w").write("\n".join(out) + "\n")
print("%s: %s" % (sys.argv[2], ", ".join(p[1] for p in parts)))
