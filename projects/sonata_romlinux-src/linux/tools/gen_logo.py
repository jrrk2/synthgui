#!/usr/bin/env python3
"""Render the 160x128 RGB565 boot logo (little-endian, row-major: what /dev/fb0 wants) with the 8x8 font of
sonata-lib/font8x8_basic.h (public domain).  usage: gen_logo.py out.rgb565"""
import re, struct, sys, pathlib

here = pathlib.Path(__file__).resolve().parent
txt = (here / "../../../sonata-lib/font8x8_basic.h").read_text()
font = {}
for i, m in enumerate(re.finditer(r"\{\s*((?:0x[0-9A-Fa-f]{2}\s*,?\s*){8})\}", txt)):
    font[i] = [int(v, 16) for v in re.findall(r"0x([0-9A-Fa-f]{2})", m.group(1))]

W, H = 160, 128
def rgb(r, g, b):
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
img = [[rgb(10, 12 + y // 5, 40 + y // 2) for x in range(W)] for y in range(H)]   # dark blue gradient

def text(s, x0, y0, scale, colour):
    for n, ch in enumerate(s):
        for row, bits in enumerate(font[ord(ch)]):
            for col in range(8):
                if bits >> col & 1:                       # bit 0 is the leftmost pixel
                    for dy in range(scale):
                        for dx in range(scale):
                            x, y = x0 + n * 8 * scale + col * scale + dx, y0 + row * scale + dy
                            if 0 <= x < W and 0 <= y < H:
                                img[y][x] = colour

def centred(s, y, scale, colour, shadow=None):
    x0 = (W - len(s) * 8 * scale) // 2
    if shadow is not None:
        text(s, x0 + 1, y + 1, scale, shadow)
    text(s, x0, y, scale, colour)

for x in range(W):                                       # a sine of sorts: the "sonata"
    import math
    y = int(30 + 14 * math.sin(x / 9.0))
    for t in range(2):
        img[y + t][x] = rgb(255, 200, 0)
centred("SONATA", 52, 3, rgb(255, 255, 255), rgb(0, 0, 0))
centred("LITEX LINUX", 84, 1, rgb(0, 255, 120))
centred("VexRiscv RV32IMAC", 98, 1, rgb(160, 180, 255))
centred("lowRISC Sonata", 112, 1, rgb(255, 160, 80))
pixels = [p for row in img for p in row]
pathlib.Path(sys.argv[1]).write_bytes(b"".join(struct.pack("<H", p) for p in pixels))

# the same image as the initial contents of the LCD frame buffer: rtl/lcd_fb_ram.v, ten directly instantiated
# RAMB36E1 (1024 x 32 each, two RGB565 pixels per word, pixel 0 in the low half).  Optional second argument: the
# directory to write lcd_fb_ram.v into.
if len(sys.argv) > 2:
    pixels += [0] * (20480 - len(pixels))
    words = [pixels[2 * i] | pixels[2 * i + 1] << 16 for i in range(10240)]
    out = ["// generated by linux/tools/gen_logo.py -- do not edit",
           "// Frame buffer of the LCD: 10240 words (2 RGB565 pixels each) in ten RAMB36E1 used as 1024 x 32, port A",
           "// write (byte enables), port B read.  The initial contents are the boot logo.",
           "module lcd_fb_ram (",
           "    input wire clk,",
           "    input wire we,",
           "    input wire [13:0] wa,",
           "    input wire [31:0] wd,",
           "    input wire [3:0] wsel,",
           "    input wire [13:0] ra,",
           "    output wire [31:0] q          // valid one clock after ra",
           ");",
           "    reg [3:0] rblk = 4'd0;",
           "    always @(posedge clk) rblk <= ra[13:10];",
           "    wire [31:0] q0, q1, q2, q3, q4, q5, q6, q7, q8, q9;"]
    for b in range(10):
        out.append("    RAMB36E1 #(.RAM_MODE(\"TDP\"), .WRITE_MODE_A(\"READ_FIRST\"), .WRITE_MODE_B(\"READ_FIRST\"),")
        out.append("        .READ_WIDTH_A(36), .WRITE_WIDTH_A(36), .READ_WIDTH_B(36), .WRITE_WIDTH_B(0), .DOA_REG(0), .DOB_REG(0),")
        for j in range(128):
            v = 0
            for w in range(8):
                v |= words[b * 1024 + j * 8 + w] << (32 * w)
            out.append("        .INIT_%02X(256'h%064x)%s" % (j, v, "," if j < 127 else ""))
        out.append("    ) fb%d (" % b)
        out.append("        .CLKARDCLK(clk), .CLKBWRCLK(clk),")
        out.append("        .ENARDEN(we && wa[13:10] == 4'd%d), .ENBWREN(1'b1)," % b)
        out.append("        .REGCEAREGCE(1'b0), .REGCEB(1'b0), .RSTRAMARSTRAM(1'b0), .RSTRAMB(1'b0), .RSTREGARSTREG(1'b0), .RSTREGB(1'b0),")
        out.append("        .WEA(wsel & {4{we && wa[13:10] == 4'd%d}}), .WEBWE(8'h00)," % b)
        out.append("        .ADDRARDADDR({1'b1, wa[9:0], 5'b00000}), .ADDRBWRADDR({1'b1, ra[9:0], 5'b00000}),")
        out.append("        .DIADI(wd), .DIPADIP(4'h0), .DIBDI(32'h0), .DIPBDIP(4'h0),")
        out.append("        .DOADO(), .DOPADOP(), .DOBDO(q%d), .DOPBDOP());" % b)
    out.append("    reg [31:0] qm;")
    out.append("    always @* begin")
    out.append("        case (rblk)")
    for b in range(10):
        out.append("            4'd%d: qm = q%d;" % (b, b))
    out.append("            default: qm = 32'h0;")
    out.append("        endcase")
    out.append("    end")
    out.append("    assign q = qm;")
    out.append("endmodule")
    (pathlib.Path(sys.argv[2]) / "lcd_fb_ram.v").write_text("\n".join(out) + "\n")
