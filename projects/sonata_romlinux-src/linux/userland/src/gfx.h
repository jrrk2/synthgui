/* draw text at (x, y), each character scale*8 pixels wide; returns the x after the last character */
static int gfx_text(int x, int y, const char *s, uint16_t c, int scale)
{
    for (; *s; s++, x += 8 * scale) {
        if (*s < 32 || *s > 126)
            continue;
        const uint8_t *g = gfx_font[*s - 32];
        for (int row = 0; row < 8; row++)
            for (int col = 0; col < 8; col++)
                if (g[row] >> col & 1)
                    gfx_rect(x + col * scale, y + row * scale, scale, scale, c, 1);
    }
    return x;
}

/* a 256-entry sine table scaled to -127..127, filled on first use; gfx_sin(a) takes a full circle as 0..255 */
static int8_t gfx_sin_tab[256];
static int gfx_sin_ready;
static int gfx_sin(int a)
{
    if (!gfx_sin_ready) {
        /* a parabola approximation of the sine, good enough for graphics, no libm needed */
        for (int i = 0; i < 256; i++) {
            int x = i < 128 ? i : i - 256;            /* -128..127 */
            int y = (x * (128 - (x < 0 ? -x : x))) / 32;  /* -127..127ish */
            gfx_sin_tab[i] = (int8_t)(y > 127 ? 127 : y < -127 ? -127 : y);
        }
        gfx_sin_ready = 1;
    }
    return gfx_sin_tab[a & 255];
}

